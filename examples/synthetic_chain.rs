//! Generate a realistic single-expiry option chain as CSV.
//!
//! Prices come from a known quadratic smile in log-moneyness plus a little
//! seeded noise, then get a bid/ask spread and are rounded to a one-cent
//! tick, so the smile fitted from the output will be close to, but not
//! exactly, the generating one. Far-OTM options trade at a zero bid, as they
//! do in real markets.
//!
//! ```text
//! cargo run --example synthetic_chain > examples/chain.csv
//! ```

use options_lab::{OptionParams, OptionType, bsm};
use rand::{Rng, SeedableRng};
use rand_chacha::ChaCha8Rng;

const SPOT: f64 = 187.40;
const RATE: f64 = 0.043;
const DIVIDEND: f64 = 0.006;
const DAYS: f64 = 45.0;

/// The "true" smile: 26% at the forward, put skew, positive curvature.
fn true_vol(k: f64) -> f64 {
    0.26 - 0.42 * k + 1.10 * k * k
}

fn main() {
    let mut rng = ChaCha8Rng::seed_from_u64(2026);
    println!("# synthetic chain generated by examples/synthetic_chain.rs");
    println!("# spot={SPOT}, rate={RATE}, dividend={DIVIDEND}, days={DAYS}");
    println!("strike,type,bid,ask");

    for strike in (140..=240).step_by(5) {
        let strike = f64::from(strike);
        let p = OptionParams::new(SPOT, strike, DAYS / 365.0)
            .with_rate(RATE)
            .with_dividend(DIVIDEND);
        let vol = true_vol(p.log_moneyness()) + rng.gen_range(-0.003..0.003);
        for kind in [OptionType::Call, OptionType::Put] {
            let fair = bsm::price(kind, &p.with_vol(vol)).expect("valid inputs");
            let half_spread = (0.03 * fair).clamp(0.02, 0.25);
            let bid = ((fair - half_spread) * 100.0).floor() / 100.0;
            let ask = ((fair + half_spread) * 100.0).ceil() / 100.0;
            println!("{strike},{kind},{:.2},{:.2}", bid.max(0.0), ask.max(0.05));
        }
    }
}
