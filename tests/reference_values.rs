const NAMES: [&str; 8] = [
    "price", "delta", "gamma", "vega", "theta", "rho", "vanna", "volga",
];

#[test]
fn bsm_matches_independent_reference() {
    for (i, c) in CASES.iter().enumerate() {
        let p = OptionParams::new(c.spot, c.strike, c.expiry)
            .with_rate(c.rate)
            .with_dividend(c.dividend)
            .with_vol(c.vol);
        for (kind, expected) in [(OptionType::Call, &c.call), (OptionType::Put, &c.put)] {
            let price = bsm::price(kind, &p).unwrap();
            let g = bsm::greeks(kind, &p).unwrap();
            let got = [
                price, g.delta, g.gamma, g.vega, g.theta, g.rho, g.vanna, g.volga,
            ];
            for ((name, got), want) in NAMES.iter().zip(got).zip(expected) {
                // Relative tolerance with an absolute floor scaled to the spot,
                // since the case set spans spot = 1.25 to 3500.
                let tol = 1e-9 * want.abs().max(1e-3 * c.spot.min(1.0));
                assert!(
                    (got - want).abs() <= tol,
                    "case {i} {kind} {name}: got {got:e}, want {want:e}"
                );
            }
        }
    }
}
